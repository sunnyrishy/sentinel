"""Build scenario files and a licence manifest from user-supplied clips (tools/make_test_set.py).

Clip folders: data/clips/<class>/*.wav for reversing_alarm, vehicle_horn and fire_alarm, and
data/clips/negative/*.wav for speech, music, tools, machinery and so on. Every clip needs a row in
the manifest CSV with a licence. Only CC0, CC-BY and own recordings are accepted (spec rule 6).
"""

from __future__ import annotations

import csv
import hashlib
import json
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import soundfile as sf
import yaml

from sentinel.config import PROJECT_ROOT, ConfigError
from sentinel.types import AlertClass

POSITIVE_DIRS = [c.value for c in AlertClass]
NEGATIVE_DIR = "negative"
AUDIO_SUFFIXES = {".wav", ".flac", ".ogg"}
MANIFEST_COLUMNS = [
    "file",
    "license",
    "attribution",
    "source_url",
    "session",
    "distance_m",
    "notes",
]
DEFAULT_LEVELS = [("easy", 10.0), ("loud", 5.0), ("very_loud", 0.0)]
BEGIN_MARK = "<!-- BEGIN generated by tools/make_test_set.py -->"
END_MARK = "<!-- END generated by tools/make_test_set.py -->"


class TestSetError(ConfigError):
    """The clips or manifest cannot be used. The message lists every problem found."""

    __test__ = False  # not a pytest class


@dataclass(frozen=True)
class Clip:
    path: Path
    rel: str  # path relative to the clips folder, forward slashes
    label: str | None  # alert class, or None for a negative clip
    duration_s: float
    license: str  # CC0, CC-BY, CC-BY-NC or own
    attribution: str
    source_url: str
    session: str
    distance_m: str
    notes: str
    split: str = "dev"

    @property
    def dev_only(self) -> bool:
        return self.license == "CC-BY-NC"


def discover(clips_dir: Path) -> list[Path]:
    found: list[Path] = []
    for sub in [*POSITIVE_DIRS, NEGATIVE_DIR]:
        d = clips_dir / sub
        if d.is_dir():
            found += sorted(p for p in d.iterdir() if p.suffix.lower() in AUDIO_SUFFIXES)
    return found


def normalize_license(text: str) -> tuple[str, str]:
    """Returns (canonical name, status). Status is ok, nc (non-commercial) or bad."""
    t = re.sub(r"[\s_]+", "-", text.strip().lower())
    if re.fullmatch(r"own(-recordings?)?", t):
        return "own", "ok"
    if t.startswith("cc0"):
        return "CC0", "ok"
    if t.startswith("cc-by-nc"):
        return "CC-BY-NC", "nc"
    if re.fullmatch(r"cc-by(-\d(\.\d)?)?", t):
        return "CC-BY", "ok"
    return text.strip(), "bad"


def read_manifest(path: Path) -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    with path.open(newline="", encoding="utf-8") as f:
        return {row["file"].strip().replace("\\", "/"): row for row in csv.DictReader(f)}


def write_skeleton(clips_dir: Path, manifest_path: Path) -> int:
    """Add a blank row for every clip that is not in the manifest yet. Returns rows added."""
    existing = read_manifest(manifest_path)
    new_rows = []
    for p in discover(clips_dir):
        rel = p.relative_to(clips_dir).as_posix()
        if rel not in existing:
            new_rows.append({c: "" for c in MANIFEST_COLUMNS} | {"file": rel})
    write_header = not manifest_path.exists()
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with manifest_path.open("a", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=MANIFEST_COLUMNS)
        if write_header:
            w.writeheader()
        w.writerows(new_rows)
    return len(new_rows)


def collect_clips(
    clips_dir: Path,
    manifest: dict[str, dict[str, str]],
    heldout_session: str | None = None,
    allow_nc: bool = False,
) -> tuple[list[Clip], list[str]]:
    """Validate licences and build Clip records. Raises TestSetError listing every problem."""
    problems: list[str] = []
    warnings: list[str] = []
    clips: list[Clip] = []
    files = discover(clips_dir)
    if not files:
        raise TestSetError(
            f"No clips found under {clips_dir}. Put wav files in "
            f"{', '.join([*POSITIVE_DIRS, NEGATIVE_DIR])} subfolders."
        )
    for p in files:
        rel = p.relative_to(clips_dir).as_posix()
        row = manifest.get(rel)
        if row is None or not (row.get("license") or "").strip():
            problems.append(f"{rel}: no licence in the manifest")
            continue
        lic, status = normalize_license(row["license"])
        if status == "bad":
            problems.append(f"{rel}: licence '{lic}' is not allowed. Use CC0, CC-BY or own")
            continue
        if lic == "CC-BY" and not (row.get("attribution") or "").strip():
            problems.append(f"{rel}: CC-BY clips need an attribution (author and title)")
            continue
        if status == "nc":
            if not allow_nc:
                warnings.append(f"skipped {rel}: CC-BY-NC is not allowed (pass --allow-nc for dev)")
                continue
            warnings.append(f"{rel} is CC-BY-NC: development only, never show it at a prize event")
        label = p.parent.name if p.parent.name in POSITIVE_DIRS else None
        session = (row.get("session") or "").strip() or "unspecified"
        split = "heldout" if heldout_session and session == heldout_session else "dev"
        try:
            duration = float(sf.info(str(p)).duration)
        except RuntimeError as err:
            problems.append(f"{rel}: cannot read audio ({err})")
            continue
        clips.append(
            Clip(
                p, rel, label, duration, lic, (row.get("attribution") or "").strip(),
                (row.get("source_url") or "").strip(), session,
                (row.get("distance_m") or "").strip(), (row.get("notes") or "").strip(), split,
            )
        )  # fmt: skip
    if problems:
        raise TestSetError("Clip problems:\n" + "\n".join(f"  {m}" for m in problems))
    if not heldout_session:
        warnings.append(
            "no --heldout-session given: everything is in the dev split, so no numbers from this "
            "set may be reported"
        )
    elif not any(c.split == "heldout" for c in clips):
        warnings.append(f"no clips have session '{heldout_session}', so the heldout split is empty")
    return clips, warnings


def parse_levels(text: str) -> list[tuple[str, float]]:
    """'easy=10,loud=5,very_loud=0' -> [('easy', 10.0), ...]. Values are signal-to-noise dB."""
    out = []
    for part in text.split(","):
        name, _, val = part.partition("=")
        if not name.strip() or not val.strip():
            raise TestSetError(f"bad --levels entry '{part}'. Use name=snr_db, e.g. loud=5")
        out.append((name.strip(), float(val)))
    return out


def _rel_to_project(p: Path) -> str:
    try:
        return p.resolve().relative_to(PROJECT_ROOT).as_posix()
    except ValueError:
        return str(p.resolve())


def _interleave(clips: list[Clip]) -> list[Clip]:
    """Round-robin across classes so no single class fills the start of a scenario."""
    by_label: dict[str, list[Clip]] = {}
    for c in clips:
        by_label.setdefault(c.label or "", []).append(c)
    queues = [by_label[k] for k in sorted(by_label)]
    out: list[Clip] = []
    while any(queues):
        for q in queues:
            if q:
                out.append(q.pop(0))
    return out


def build_scenarios(
    clips: list[Clip],
    levels: list[tuple[str, float]],
    noise_type: str = "pink",
    noise_dbfs: float = -30.0,
    gap_s: float = 10.0,
    max_scenario_s: float = 600.0,
    noise_only_s: float = 300.0,
    origin: str = "real",
    prefix: str = "testset",
    seed: int = 1,
) -> list[dict[str, Any]]:
    """Scenario dicts (valid scenario YAML) for every split and noise level.

    gap_s must exceed the alert time to live plus the cooldown (3 s + 5 s by default) so that two
    events of the same class are never merged by the policy's cooldown.
    """
    scenarios: list[dict[str, Any]] = []
    counter = 0

    def new(
        name: str, split: str, level: str, events: list[dict[str, Any]], duration: float
    ) -> dict[str, Any]:
        nonlocal counter
        counter += 1
        return {
            "name": name, "duration_s": round(duration, 3), "seed": seed + counter,
            "origin": origin, "split": split, "level": level,
            "noise": {"type": noise_type, "level_dbfs": noise_dbfs}, "events": events,
        }  # fmt: skip

    for split in ("dev", "heldout"):
        in_split = [c for c in clips if c.split == split]
        if not in_split:
            continue
        for level, snr in levels:
            for kind, group in (
                ("pos", _interleave([c for c in in_split if c.label])),
                ("neg", [c for c in in_split if not c.label]),
            ):
                part, events, cursor = 1, [], 3.0 if kind == "pos" else 1.0
                for clip in group:
                    if events and cursor + clip.duration_s > max_scenario_s:
                        name = f"{prefix}_{split}_{level}_{kind}_{part:02d}"
                        scenarios.append(new(name, split, level, events, cursor + 2.0))
                        part, events, cursor = part + 1, [], 3.0 if kind == "pos" else 1.0
                    events.append(
                        {"kind": "clip", "path": _rel_to_project(clip.path),
                         "start_s": round(cursor, 3), "snr_db": snr, "label": clip.label}
                    )  # fmt: skip
                    cursor += clip.duration_s + (gap_s if kind == "pos" else 2.0)
                if events:
                    name = f"{prefix}_{split}_{level}_{kind}_{part:02d}"
                    scenarios.append(new(name, split, level, events, cursor + 2.0))
            scenarios.append(
                new(f"{prefix}_{split}_{level}_noise_only", split, level, [], noise_only_s)
            )
    return scenarios


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_scenarios(scenarios: list[dict[str, Any]], out_dir: Path, origin: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for sc in scenarios:
        path = out_dir / f"{sc['name']}.yaml"
        header = f"# Generated by tools/make_test_set.py. origin: {origin}. Do not edit by hand.\n"
        path.write_text(header + yaml.safe_dump(sc, sort_keys=False), encoding="utf-8")
        paths.append(path)
    return paths


def write_manifest(
    out_dir: Path,
    clips: list[Clip],
    scenarios: list[dict[str, Any]],
    warnings: list[str],
    params: dict[str, Any],
) -> Path:
    data = {
        "generated": datetime.now(UTC).isoformat(timespec="seconds"),
        "parameters": params,
        "warnings": warnings,
        "clips": [
            {
                "file": c.rel,
                "label": c.label or "negative",
                "license": c.license,
                "attribution": c.attribution,
                "source_url": c.source_url,
                "session": c.session,
                "distance_m": c.distance_m,
                "split": c.split,
                "duration_s": round(c.duration_s, 3),
                "sha256": sha256_of(c.path),
                "dev_only": c.dev_only,
            }
            for c in clips
        ],
        "scenarios": [
            {
                "name": s["name"],
                "split": s["split"],
                "level": s["level"],
                "duration_s": s["duration_s"],
                "events": len(s["events"]),
            }
            for s in scenarios
        ],
    }
    path = out_dir / "manifest.json"
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return path


def update_attributions(path: Path, clips: list[Clip]) -> None:
    """Rewrite the generated block of data/ATTRIBUTIONS.md. Everything outside it is kept."""
    rows = ["| File | Licence | Attribution | Source |", "|---|---|---|---|"]
    for c in clips:
        rows.append(
            f"| {c.rel} | {c.license} | {c.attribution or 'own recording'} "
            f"| {c.source_url or '-'} |"
        )
    block = f"{BEGIN_MARK}\n" + "\n".join(rows) + f"\n{END_MARK}"
    text = path.read_text(encoding="utf-8") if path.exists() else "# Attributions\n\n"
    if BEGIN_MARK in text and END_MARK in text:
        head, rest = text.split(BEGIN_MARK, 1)
        _, tail = rest.split(END_MARK, 1)
        text = head + block + tail
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
